_DUHI_RE = re.compile(r"(?<![а-яёa-z])духи(?![а-яёa-z])", re.IGNORECASE)


def _norm(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value or "").strip().lower().replace("ё", "е"))


def non_food_reason(
    *,
    name: str | None = None,
    brand: str | None = None,
    category: str | None = None,
) -> str | None:
    """Возвращает причину, если товар явно непищевой, иначе None."""
    text = _norm(name)
    category_text = _norm(category)

    for marker in _NON_FOOD_CATEGORY_MARKERS:
        if marker in category_text:
            return f"category:{marker}"

    if _DUHI_RE.search(text):
        return "name:духи"

    for marker in _NON_FOOD_NAME_MARKERS:
        if marker in text:
            return f"name:{marker}"
    return None
