def normalize_for_connector(name: str) -> str:
    """Возвращает каноническое имя для группировки в экспорте.

    Правила:
      1. Если имя в CANONICAL_ALIASES — вернуть канонический вариант.
      2. Убрать содержимое скобок: "яйцо (куриное)" -> "яйцо".
      3. Если содержит PRODUCT_DEFINING — оставить как есть (разные продукты).
      4. Иначе отрезать PREP_MODIFIERS.
      5. Если после отрезания пусто — вернуть оригинал.

    Примеры:
      "Яйцо варёное" -> "яйцо"
      "Яйцо куриное" -> "яйцо"
      "Яйцо перепелиное" -> "яйцо перепелиное"  (PRODUCT_DEFINING)
      "Куриная грудка отварная" -> "куриная грудка"
      "Лук репчатый крупный" -> "лук репчатый"
    """
    if not name:
        return ""

    n = name.strip().lower()

    # 1. Прямое совпадение
    if n in CANONICAL_ALIASES:
        return CANONICAL_ALIASES[n]

    # 2. Убираем скобки: "яйцо (куриное)" -> "яйцо"
    n_clean = re.sub(r"\s*\([^)]*\)", "", n).strip()
    if n_clean in CANONICAL_ALIASES:
        return CANONICAL_ALIASES[n_clean]

    # 3. Проверяем PRODUCT_DEFINING
    for kw in PRODUCT_DEFINING:
        if kw in n_clean:
            return n_clean

    # 4. Отрезаем PREP_MODIFIERS
    tokens = n_clean.split()
    filtered = [t for t in tokens if t not in PREP_MODIFIERS]

    if filtered and len(filtered) < len(tokens):
        result = " ".join(filtered)
        # Повторная проверка по alias (например, "яйца варёные" -> "яйца" -> "яйцо")
        if result in CANONICAL_ALIASES:
            return CANONICAL_ALIASES[result]
        return result

    return n_clean
