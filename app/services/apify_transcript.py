"""Apify: единственный источник транскриптов YouTube.

Схема:
  1. Проверяем локальный кэш (SQLite) по video_id.
  2. Если нет — запускаем Apify Actor синхронно и забираем dataset items.
  3. Гибко вытаскиваем текст (transcript_text / transcript / text / segments).
  4. Кэшируем текст, чтобы не тратить кредиты повторно.

Токен никогда не логируется: все сообщения об ошибках проходят через
`_mask()`, который вырезает `APIFY_TOKEN`.
"""
from __future__ import annotations

import time
from typing import Any

import httpx

from config import (
    APIFY_ACTOR_ID,
    APIFY_BASE_URL,
    APIFY_QUOTA_LIMIT_USD,
    APIFY_STOP_RATIO,
    APIFY_TIMEOUT,
    APIFY_TOKEN,
)
from stores.youtube_transcripts import youtube_transcripts


class ApifyError(Exception):
    """Понятная ошибка Apify (без токена в тексте)."""

    def __init__(self, message: str, *, status: int | None = None) -> None:
        super().__init__(message)
        self.message = message
        self.status = status


def _mask(text: str) -> str:
    if APIFY_TOKEN:
        return text.replace(APIFY_TOKEN, "***")
    return text


def _actor_path() -> str:
    """`user/actor` → `user~actor` (формат Apify API)."""
    actor = APIFY_ACTOR_ID.strip()
    if "~" in actor:
        return actor
    return actor.replace("/", "~", 1)


def _text_from(value: Any) -> str:
    """Достаёт текст из строки / списка строк / списка объектов."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, list):
        parts: list[str] = []
        for item in value:
            if isinstance(item, str):
                parts.append(item)
            elif isinstance(item, dict):
                txt = item.get("text") or item.get("transcript") or ""
                if txt:
                    parts.append(str(txt))
        return " ".join(p.strip() for p in parts if p and p.strip()).strip()
    if isinstance(value, dict):
        return _text_from(value.get("text") or value.get("transcript"))
    return ""


def extract_transcript_text(item: dict[str, Any]) -> str:
    """Гибкий парсер ответа: структура зависит от актора."""
    for key in ("transcript_text", "transcript", "text"):
        text = _text_from(item.get(key))
        if text:
            return text
    # Фолбэк: склеиваем сегменты с таймкодами.
    segments = item.get("segments") or item.get("captions")
    return _text_from(segments)


async def fetch_transcript(
    url: str,
    video_id: str,
    *,
    use_cache: bool = True,
) -> dict[str, Any]:
    """Возвращает {'text', 'title', 'channel', 'language', 'source', 'cached'}."""
    if use_cache:
        cached = await youtube_transcripts.get(video_id)
        if cached and (cached.get("transcript") or "").strip():
            print(f"[apify] cache hit video={video_id}")
            return {
                "text": cached["transcript"],
                "title": cached.get("title"),
                "channel": cached.get("channel"),
                "language": cached.get("language"),
                "source": "cache",
                "cached": True,
            }

    if not APIFY_TOKEN:
        raise ApifyError(
            "Apify не настроен: задайте APIFY_TOKEN в окружении "
            "(или в опции apify_token аддона) и перезапустите приложение."
        )

    payload = {
        "videos": [url],
        "includeTimestamps": False,
        "includeAutoGenerated": True,
    }
    endpoint = (
        f"{APIFY_BASE_URL}/acts/{_actor_path()}"
        "/run-sync-get-dataset-items"
    )
    try:
        async with httpx.AsyncClient(timeout=APIFY_TIMEOUT) as client:
            resp = await client.post(
                endpoint,
                params={"token": APIFY_TOKEN},
                json=payload,
            )
    except httpx.TimeoutException as exc:
        raise ApifyError(
            f"Apify не ответил за {int(APIFY_TIMEOUT)} с. Попробуйте позже."
        ) from exc
    except httpx.HTTPError as exc:
        raise ApifyError(f"Не удалось связаться с Apify: {_mask(str(exc))}") from exc

    if resp.status_code == 401:
        raise ApifyError(
            "Apify отклонил токен (401). Проверьте APIFY_TOKEN.", status=401
        )
    if resp.status_code == 402:
        raise ApifyError(
            "Apify: закончились кредиты или достигнут лимит расходов (402).",
            status=402,
        )
    if resp.status_code >= 400:
        raise ApifyError(
            f"Apify вернул HTTP {resp.status_code}: {_mask(resp.text[:300])}",
            status=resp.status_code,
        )

    try:
        data = resp.json()
    except ValueError as exc:
        raise ApifyError("Apify вернул не-JSON ответ") from exc

    if isinstance(data, dict):
        err = data.get("error") or {}
        message = err.get("message") if isinstance(err, dict) else str(err)
        raise ApifyError(f"Apify вернул ошибку: {_mask(str(message or data))[:300]}")

    if not isinstance(data, list) or not data:
        raise ApifyError(
            "Apify вернул пустой dataset: актор не нашёл видео или транскрипт."
        )

    item = next(
        (
            row
            for row in data
            if isinstance(row, dict) and row.get("videoId") == video_id
        ),
        data[0],
    )
    if not isinstance(item, dict):
        raise ApifyError("Неожиданная структура ответа Apify (ожидался объект).")

    status = str(item.get("status") or "").lower()
    if status and status != "ok":
        reason = item.get("error") or f"статус {status}"
        raise ApifyError(f"Транскрипт недоступен: {reason}")

    text = extract_transcript_text(item)
    if not text.strip():
        keys = ", ".join(sorted(item.keys())[:8])
        raise ApifyError(
            "Не удалось распознать структуру ответа Apify: нет полей "
            f"transcript_text / transcript / text (поля: {keys})."
        )

    title = item.get("title")
    channel = item.get("channel")
    language = item.get("transcriptLanguage")
    await youtube_transcripts.upsert(
        video_id,
        text,
        url=url,
        title=title,
        channel=channel,
        language=language,
        source="apify",
    )
    print(
        f"[apify] transcript ok video={video_id} chars={len(text)} "
        f"lang={language} title={str(title)[:60]}"
    )
    return {
        "text": text,
        "title": title,
        "channel": channel,
        "language": language,
        "source": "apify",
        "cached": False,
    }


# --- Лимиты / баланс -------------------------------------------------------

_usage_cache: dict[str, Any] = {"at": 0.0, "data": None}
_USAGE_TTL = 60.0


def _empty_quota(reason: str) -> dict[str, Any]:
    return {
        "available": False,
        "blocked": True,
        "reason": reason,
        "used_usd": 0.0,
        "limit_usd": APIFY_QUOTA_LIMIT_USD,
        "percent": 0.0,
        "stop_ratio": APIFY_STOP_RATIO,
        "checked_at": int(time.time()),
    }


async def get_usage(*, force: bool = False) -> dict[str, Any]:
    """Возвращает расход и лимит Apify.

    blocked=True, если расход достиг APIFY_STOP_RATIO от лимита
    (по умолчанию 90%) или токен не задан.
    """
    now = time.time()
    if (
        not force
        and _usage_cache["data"] is not None
        and now - float(_usage_cache["at"]) < _USAGE_TTL
    ):
        return _usage_cache["data"]

    if not APIFY_TOKEN:
        data = _empty_quota("token_missing")
        _usage_cache.update(at=now, data=data)
        return data

    endpoint = f"{APIFY_BASE_URL}/users/me/limits"
    try:
        async with httpx.AsyncClient(timeout=min(APIFY_TIMEOUT, 30)) as client:
            resp = await client.get(endpoint, params={"token": APIFY_TOKEN})
        if resp.status_code >= 400:
            raise ApifyError(
                f"HTTP {resp.status_code}: {_mask(resp.text[:200])}",
                status=resp.status_code,
            )
        payload = resp.json()
    except Exception as exc:  # noqa: BLE001
        # Не блокируем импорт из-за сбоя мониторинга — работаем fail-open.
        data = _empty_quota("limits_unavailable")
        data["available"] = True
        data["blocked"] = False
        data["error"] = _mask(str(exc))[:300]
        _usage_cache.update(at=now, data=data)
        print(f"[apify] limits error: {data['error']}")
        return data

    info = payload.get("data") if isinstance(payload, dict) else None
    current = (info or {}).get("current") or {}
    limits = (info or {}).get("limits") or {}

    used = float(current.get("monthlyUsageUsd") or 0)
    limit = float(limits.get("maxMonthlyUsageUsd") or APIFY_QUOTA_LIMIT_USD)
    if limit <= 0:
        limit = APIFY_QUOTA_LIMIT_USD
    percent = min(100.0, used / limit * 100.0) if limit else 0.0
    blocked = used >= limit * APIFY_STOP_RATIO

    data = {
        "available": True,
        "blocked": blocked,
        "reason": "quota" if blocked else None,
        "used_usd": round(used, 4),
        "limit_usd": round(limit, 2),
        "percent": round(percent, 1),
        "stop_ratio": APIFY_STOP_RATIO,
        "checked_at": int(now),
        "actor": APIFY_ACTOR_ID,
    }
    _usage_cache.update(at=now, data=data)
    print(
        f"[apify] usage ${used:.2f} / ${limit:.2f} ({percent:.1f}%) "
        f"blocked={blocked}"
    )
    return data


def reset_usage_cache() -> None:
    _usage_cache.update(at=0.0, data=None)
